#!/usr/bin/env node
// Generates src/supabaseConfig.ts — for the same reason the Android app's app/build.gradle.kts
// injects BuildConfig fields: the values themselves aren't secret (RLS is the real line of defense),
// but they're filled in here instead of as source literals to keep them out of the public repo's
// history (see the android-moonkata-reader repo's SYNC_MULTIUSER_PLAN.md stage 3). Uses the
// SUPABASE_URL/SUPABASE_PUBLISHABLE_KEY environment variables if present, otherwise reads them from
// .env.local at the repo root (gitignored, KEY=VALUE lines). If neither is present, it generates
// empty strings, in which case the extension still compiles/runs fine — only the sync feature is
// silently disabled.

const fs = require('fs');
const path = require('path');

function loadEnvLocal() {
	const envPath = path.join(__dirname, '..', '.env.local');
	if (!fs.existsSync(envPath)) return {};
	const result = {};
	for (const line of fs.readFileSync(envPath, 'utf8').split('\n')) {
		const trimmed = line.trim();
		if (!trimmed || trimmed.startsWith('#')) continue;
		const idx = trimmed.indexOf('=');
		if (idx === -1) continue;
		result[trimmed.slice(0, idx).trim()] = trimmed.slice(idx + 1).trim();
	}
	return result;
}

const envLocal = loadEnvLocal();
const url = process.env.SUPABASE_URL ?? envLocal.SUPABASE_URL ?? '';
const key = process.env.SUPABASE_PUBLISHABLE_KEY ?? envLocal.SUPABASE_PUBLISHABLE_KEY ?? '';

const content = `// This file is auto-generated by scripts/generate-supabase-config.js — editing it directly will be
// overwritten the next time "npm run compile"/"npm run watch" runs. Values are filled in from
// environment variables or .env.local.
export const SUPABASE_URL = ${JSON.stringify(url)};
export const SUPABASE_PUBLISHABLE_KEY = ${JSON.stringify(key)};
`;

fs.writeFileSync(path.join(__dirname, '..', 'src', 'supabaseConfig.ts'), content);
